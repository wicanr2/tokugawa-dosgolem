"""逐索引核對單位來源及透明裁切；不推定原版兵種名稱。"""
import argparse
import hashlib
import json
import os
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version


LEGACY = {1:([2,0,47,48],[265,39,1098,1191]),3:([0,0,41,48],[117,90,984,1159])}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepared_sprite(asset, bounds, crop):
    out = Image.new('RGBA',(96,96))
    width,height = (bounds[2]-bounds[0])*2,(bounds[3]-bounds[1])*2
    for y in range(height):
        for x in range(width):
            out.putpixel((bounds[0]*2+x,bounds[1]*2+y),asset.getpixel((crop[0]+x*(crop[2]-crop[0])//width,crop[1]+y*(crop[3]-crop[1])//height)))
    return out


def main():
    assert Path('/.dockerenv').is_file() and os.getuid() == 1000 and pillow_version == '9.4.0'
    parser = argparse.ArgumentParser()
    parser.add_argument('--integrate',action='store_true')
    args = parser.parse_args()
    project, root = Path('/project'), Path('/output')
    terrain = project/'workplace/hd-prototype/catalog/terrain'
    assert root.stat().st_uid == 1000
    if args.integrate:
        manifest_path,review_path = root/'draft-profiles.json',root/'review.json'
        manifest,review = json.loads(manifest_path.read_text()),json.loads(review_path.read_text())
        assert review['verified'] and review['reviewed_indices'] == list(range(10))
        assert review['empty_indices'] == [10,11,12] and review['draft_profiles_sha256'] == sha(manifest_path)
        assert manifest['tool_sha256'] == sha(Path(__file__))
        assert all(r['asset'].endswith('-v2.png') for r in manifest['records'] if r['index'] in [2,6,7,8])
        lines = ['// Code generated by tools/hd-unit-prepare.py; DO NOT EDIT.','package main','import "image"',
                 '// 來源索引保留原名，不以推測的兵種或武將命名。',
                 'type hdTerrainUnitProfile struct { Asset, AssetSHA string; SourceBounds, Crop image.Rectangle }',
                 'var hdTerrainUnitProfiles = map[int]hdTerrainUnitProfile{']
        for record in manifest['records']:
            if not record['asset']:
                continue
            assert sha(terrain/'art'/record['asset']) == record['asset_sha256']
            q=json.dumps
            a,b=','.join(map(str,record['source_bounds'])),','.join(map(str,record['crop']))
            lines.append(f'{record["index"]}: {{{q(record["asset"])}, {q(record["asset_sha256"])}, image.Rect({a}), image.Rect({b})}},')
        lines += ['}','']
        target=project/'tools/hd-terrain-unit-profiles.go'
        assert target.stat().st_uid == 1000
        target.write_text('\n'.join(lines))
        target=root/'profiles.json'
        assert not target.exists(), 'preserve previous integration'
        target.write_text(json.dumps({**manifest,'classification':'reviewed 10 nonempty unit HD profiles; three original empty sources preserved',
                                      'draft_profiles_sha256':sha(manifest_path),'review_sha256':sha(review_path)},ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({'source_slots':13,'approved_nonempty_units':10,'empty_indices':[10,11,12]}))
        return
    source_path=terrain/'objects/source-profiles.json'
    source_profiles=json.loads(source_path.read_text())
    native={r['index']:r for r in source_profiles['records'] if r['group']=='units'}
    assert set(native) == set(range(13))
    generation=json.loads((terrain/'art/generation.json').read_text())
    selected={int(r['name'].split('-')[1]):{'asset':r['asset'],'asset_sha256':r['sha256'],
                                        'prompt':r['prompt_file'],'prompt_sha256':r['prompt_sha256']}
              for r in generation['records'] if r['name'].startswith('unit-')}
    for path in [terrain/'art/unit-revisions.json',root/'pose-revisions-v2.json']:
        for record in json.loads(path.read_text())['records']:
            selected[record['source_index']]=record
    assert set(selected)==set(range(10))
    prepared=root/'prepared';prepared.mkdir(exist_ok=True)
    assert prepared.stat().st_uid==1000
    records=[]
    for i,source in sorted(native.items()):
        path=terrain/'objects'/source['source']
        assert sha(path)==source['source_png_sha256']
        original=Image.open(path).convert('RGBA')
        assert original.size==(48,48)
        bounds=original.getchannel('A').getbbox()
        record={'index':i,'source':str(path.relative_to(project)),'source_png_sha256':sha(path),
                'source_indices_sha256':source['indices_sha256'],'source_bounds':list(bounds) if bounds else [0,0,0,0],
                'asset':'','asset_sha256':'','crop':[0,0,0,0]}
        if bounds is None:
            assert i in [10,11,12] and source['opaque_pixels']==0
            records.append(record);continue
        assert i<10 and source['opaque_pixels']>0
        art=selected[i];asset_path=terrain/'art'/art['asset']
        assert sha(asset_path)==art['asset_sha256'] and sha(terrain/'art'/art['prompt'])==art['prompt_sha256']
        asset=Image.open(asset_path).convert('RGBA');alpha=asset.getchannel('A')
        assert asset.width==asset.height and 48<=asset.width<=8192 and alpha.getextrema()==(0,255)
        hard=alpha.point(lambda a:255 if a>7 else 0).getbbox()
        assert hard
        crop=[max(0,hard[0]-3),max(0,hard[1]-3),min(asset.width,hard[2]+3),min(asset.height,hard[3]+3)]
        if i in LEGACY:
            assert (list(bounds),crop)==LEGACY[i], 'existing source/crop changed'
        sprite=prepared_sprite(asset,bounds,crop)
        preview=prepared/f'unit-{i:03d}-hd-preview.png'
        assert not preview.exists(), 'preserve previous preparation'
        sprite.save(preview)
        record.update(asset=art['asset'],asset_sha256=art['asset_sha256'],prompt=art['prompt'],prompt_sha256=art['prompt_sha256'],
                      crop=crop,alpha_threshold=7,crop_margin=3,prepared=str(preview.relative_to(root)),prepared_sha256=sha(preview))
        records.append(record)
    pages=[]
    for page in range(2):
        sheet=Image.new('RGB',(800,720),(222,216,197));draw=ImageDraw.Draw(sheet)
        for slot,r in enumerate(records[page*5:(page+1)*5]):
            x,y=slot%2*400,slot//2*240
            original=Image.open(project/r['source']).convert('RGBA').resize((192,192),Image.Resampling.NEAREST)
            hd=Image.open(root/r['prepared']).convert('RGBA').resize((192,192),Image.Resampling.NEAREST)
            draw.text((x+4,y+4),f"units {r['index']:03d}  original / HD",fill=(0,0,0))
            sheet.paste(original,(x+4,y+24),original);sheet.paste(hd,(x+204,y+24),hd)
        path=root/f'review-page-{page+1:02d}.png';assert not path.exists();sheet.save(path)
        pages.append({'path':path.name,'sha256':sha(path)})
    gallery=Image.new('RGB',(5*288,2*312),(222,216,197));draw=ImageDraw.Draw(gallery)
    for r in records[:10]:
        i=r['index'];im=Image.open(root/r['prepared']).convert('RGBA').resize((288,288),Image.Resampling.NEAREST)
        draw.text((i%5*288+4,i//5*312+4),f'units {i:03d}',fill=(0,0,0));gallery.paste(im,(i%5*288,i//5*312+24),im)
    path=root/'unit-HD-gallery-v2.png';assert not path.exists();gallery.save(path)
    result={'classification':'unit original-source and generated-art crop review, not original unit-rule mapping',
            'tool_sha256':sha(Path(__file__)),'source_profiles_sha256':sha(source_path),
            'pose_revisions_sha256':sha(root/'pose-revisions-v2.json'),'source_slots':13,'nonempty_sources':10,'empty_indices':[10,11,12],
            'scale':2,'alpha_threshold':7,'crop_margin':3,'unchanged_normal_unit_indices':[1,3],
            'review_pages':pages,'gallery':path.name,'gallery_sha256':sha(path),'records':records}
    path=root/'draft-profiles.json';assert not path.exists();path.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'source_slots':13,'nonempty':10,'empty':3,'gallery_sha256':result['gallery_sha256']}))


if __name__=='__main__':
    main()
