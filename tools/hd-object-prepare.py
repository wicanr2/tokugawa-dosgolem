"""逐索引核對 26 項物件來源，保留兩個空白格及既有樹叢裁切。"""
import argparse
import hashlib
import json
import os
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepared_sprite(asset, bounds, crop):
    out = Image.new('RGBA', (96, 96))
    width, height = (bounds[2]-bounds[0])*2, (bounds[3]-bounds[1])*2
    for y in range(height):
        for x in range(width):
            out.putpixel((bounds[0]*2+x, bounds[1]*2+y), asset.getpixel(
                (crop[0]+x*(crop[2]-crop[0])//width, crop[1]+y*(crop[3]-crop[1])//height)))
    return out


def main():
    assert Path('/.dockerenv').is_file() and os.getuid() == 1000 and pillow_version == '9.4.0'
    parser = argparse.ArgumentParser()
    parser.add_argument('--integrate', action='store_true')
    args = parser.parse_args()
    project, root = Path('/project'), Path('/output')
    terrain = project/'workplace/hd-prototype/catalog/terrain'
    assert root.stat().st_uid == root.stat().st_gid == 1000
    if args.integrate:
        manifest_path, review_path = root/'draft-profiles.json', root/'review.json'
        manifest, review = [json.loads(p.read_text()) for p in [manifest_path, review_path]]
        assert review['verified'] and review['reviewed_indices'] == list(range(24))
        approved = review['approved_indices']
        assert approved == sorted(set(approved)) and 0 in approved and set(approved) <= set(range(24))
        assert review['empty_indices'] == [24, 25] and review['draft_profiles_sha256'] == sha(manifest_path)
        assert manifest['tool_sha256'] == sha(Path(__file__))
        lines = ['// Code generated by tools/hd-object-prepare.py; DO NOT EDIT.', 'package main', 'import "image"',
                 '// 只記來源索引與呈現幾何，不推定地圖物件用途。',
                 'type hdTerrainObjectProfile struct { Asset, AssetSHA string; SourceBounds, Crop image.Rectangle }',
                 'var hdTerrainObjectProfiles = map[int]hdTerrainObjectProfile{']
        for r in manifest['records']:
            if r['index'] not in approved:
                continue
            assert sha(terrain/'art'/r['asset']) == r['asset_sha256']
            a, b = ','.join(map(str, r['source_bounds'])), ','.join(map(str, r['crop']))
            lines.append(f'{r["index"]}: {{{json.dumps(r["asset"])}, {json.dumps(r["asset_sha256"])}, image.Rect({a}), image.Rect({b})}},')
        lines += ['}', '']
        target = project/'tools/hd-terrain-object-profiles.go'
        assert not target.exists()
        assert target.parent.stat().st_uid == 1000
        target.write_text('\n'.join(lines))
        target = root/'profiles.json'
        assert not target.exists()
        target.write_text(json.dumps({**manifest, 'classification': 'reviewed object HD profiles; unapproved wall geometry remains draft; two original empty sources preserved',
                                     'approved_indices': approved,
                                     'draft_profiles_sha256': sha(manifest_path), 'review_sha256': sha(review_path)}, ensure_ascii=False, indent=2)+'\n')
        print(json.dumps({'approved_nonempty_objects': len(approved), 'empty_indices': [24, 25]}))
        return
    source_path = terrain/'objects/source-profiles.json'
    native = {r['index']: r for r in json.loads(source_path.read_text())['records'] if r['group'] == 'objects'}
    assert set(native) == set(range(26))
    initial = json.loads((terrain/'art/object-generation.json').read_text())
    selected = {r['index']: r for r in initial['records']}
    for r in json.loads((terrain/'art/object-generation-expanded.json').read_text())['records']:
        selected[r['source_index']] = r
    selected[0] = {'asset': 'object-000-hd-b-v2.png', 'asset_sha256': 'f6885ec6d1d557973fdb304fca537e095eec4c65e37439340ef2c39da2d94cd2',
                   'prompt': 'object-000-hd-b-v2.prompt.txt'}
    selected[0]['prompt_sha256'] = sha(terrain/'art'/selected[0]['prompt'])
    assert set(selected) == set(range(24))
    prepared = root/'prepared'
    assert not prepared.exists()
    prepared.mkdir()
    records = []
    for i, source in sorted(native.items()):
        path = terrain/'objects'/source['source']
        assert sha(path) == source['source_png_sha256']
        original = Image.open(path).convert('RGBA')
        assert original.size == (48, 48)
        bounds = original.getchannel('A').getbbox()
        r = {'index': i, 'source': str(path.relative_to(project)), 'source_png_sha256': sha(path),
             'source_indices_sha256': source['indices_sha256'], 'source_bounds': list(bounds) if bounds else [0,0,0,0],
             'asset': '', 'asset_sha256': '', 'crop': [0,0,0,0]}
        if bounds is None:
            assert i in [24, 25] and source['opaque_pixels'] == 0
            records.append(r)
            continue
        art = selected[i]
        asset_path, prompt_path = terrain/'art'/art['asset'], terrain/'art'/art['prompt']
        assert sha(asset_path) == art['asset_sha256'] and sha(prompt_path) == art['prompt_sha256']
        asset = Image.open(asset_path).convert('RGBA')
        alpha = asset.getchannel('A')
        assert asset.width == asset.height and 48 <= asset.width <= 8192 and alpha.getextrema() == (0,255)
        hard = alpha.point(lambda a: 255 if a > 7 else 0).getbbox()
        assert hard
        margin = 0 if i in list(range(4,18))+[20,21] else 3
        crop = [max(0,hard[0]-margin), max(0,hard[1]-margin), min(asset.width,hard[2]+margin), min(asset.height,hard[3]+margin)]
        if i == 0:
            assert list(bounds) == [0,0,47,47] and crop == [7,0,1247,1245]
        preview = prepared/f'object-{i:03d}-hd-preview.png'
        prepared_sprite(asset, bounds, crop).save(preview)
        r.update(asset=art['asset'], asset_sha256=art['asset_sha256'], prompt=art['prompt'], prompt_sha256=art['prompt_sha256'],
                 crop=crop, alpha_threshold=7, crop_margin=margin, prepared=str(preview.relative_to(root)), prepared_sha256=sha(preview))
        records.append(r)
    pages = []
    for page in range(4):
        sheet = Image.new('RGB',(1200,480),(222,216,197))
        draw = ImageDraw.Draw(sheet)
        for slot, r in enumerate(records[page*6:page*6+6]):
            x, y = slot%3*400, slot//3*240
            original = Image.open(project/r['source']).convert('RGBA').resize((192,192),Image.Resampling.NEAREST)
            hd = Image.open(root/r['prepared']).convert('RGBA').resize((192,192),Image.Resampling.NEAREST)
            draw.text((x+4,y+4),f"objects {r['index']:03d}  original / HD",fill=(0,0,0))
            sheet.paste(original,(x+4,y+24),original)
            sheet.paste(hd,(x+204,y+24),hd)
        path = root/f'review-page-{page+1:02d}.png'
        assert not path.exists()
        sheet.save(path)
        pages.append({'path':path.name,'sha256':sha(path)})
    gallery = Image.new('RGB',(6*192,4*216),(222,216,197))
    draw = ImageDraw.Draw(gallery)
    for r in records[:24]:
        i = r['index']
        im = Image.open(root/r['prepared']).convert('RGBA').resize((192,192),Image.Resampling.NEAREST)
        draw.text((i%6*192+4,i//6*216+4),f'objects {i:03d}',fill=(0,0,0))
        gallery.paste(im,(i%6*192,i//6*216+24),im)
    path = root/'object-HD-gallery-v1.png'
    assert not path.exists()
    gallery.save(path)
    result = {'classification':'object original-source and generated-art crop review; not original map semantics',
              'tool_sha256':sha(Path(__file__)), 'source_profiles_sha256':sha(source_path),
              'source_slots':26, 'nonempty_sources':24, 'empty_indices':[24,25], 'scale':2, 'alpha_threshold':7,
              'unchanged_normal_object_indices':[0], 'connected_wall_crop_margin':0,
              'review_pages':pages, 'gallery':path.name, 'gallery_sha256':sha(path), 'records':records}
    path = root/'draft-profiles.json'
    assert not path.exists()
    path.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'source_slots':26,'nonempty':24,'empty':2,'gallery_sha256':sha(root/result['gallery'])}))


if __name__ == '__main__':
    main()
