"""以已核對的正常 DAC 準備地面來源及編譯期對照；不是正式素材包格式。"""
import hashlib
import io
import json
import os
from pathlib import Path

from PIL import Image, __version__ as pillow_version

REVIEWED = (0, 2, 6, 13, 15, 22, 62, 67)
VARIANTS = {6: 2, 22: 2}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    assert Path("/.dockerenv").is_file() and os.getuid() == 1000 and pillow_version == "9.4.0"
    project = Path("/project")
    catalog = project/"workplace/hd-prototype/catalog"
    root = Path("/output")/"prepared"
    root.mkdir(exist_ok=True)
    sources = root/"sources"
    sources.mkdir(exist_ok=True)
    assert root.stat().st_uid == sources.stat().st_uid == 1000
    evidence_path = catalog/"terrain/trace/native-floor-palette-verification.json"
    evidence = json.loads(evidence_path.read_text())
    assert len(evidence["matched_rectangles"]) == 50
    palette_path = project/evidence["palette_capture"]
    assert sha(palette_path.read_bytes()) == evidence["palette_capture_sha256"]
    capture = json.loads(palette_path.read_text())
    palette = [tuple(c[k] for k in ("R", "G", "B")) for c in capture["palette_at_loader_return"]]
    assert [list(c) for c in palette] == evidence["palette"]
    idx = (catalog/"decoded/MAP_CHIP.OZM.idx").read_bytes()
    assert len(idx) == 640*400 and sha(idx) == evidence["source_indices_sha256"]
    extraction_path = catalog/"terrain/terrain-extraction.json"
    extraction = json.loads(extraction_path.read_text())
    assert extraction["indices_sha256"] == sha(idx)
    assert extraction["tool_sha256"] == sha((project/"tools/hd-terrain-extract.py").read_bytes())
    original = {r["source_grid_index"]: r for r in extraction["records"] if r["group"] == "floor"}
    assert len(original) == 104
    atlas = Image.frombytes("RGB", (640, 400), bytes(c for i in idx for c in palette[i]))
    trace = json.loads((catalog/"terrain/trace/verification.json").read_text())
    records = []
    for i in range(104):
        x, y = i%13*48, i//13*32
        raw = b"".join(idx[row*640+x:row*640+x+48] for row in range(y, y+32))
        assert sha(raw) == original[i]["indices_sha256"]
        name = f"floor-{i:03d}"
        buf = io.BytesIO()
        atlas.crop((x, y, x+48, y+32)).save(buf, format="PNG")
        data = buf.getvalue()
        target = sources/(name+"-original.png")
        assert not target.exists() or target.stat().st_uid == 1000 and target.read_bytes() == data
        target.write_bytes(data)
        asset = f"{name}-hd-b-v{VARIANTS.get(i, 1)}.png" if i in REVIEWED else ""
        asset_sha = ""
        if asset:
            path = catalog/"terrain/art"/asset
            with Image.open(path) as hd:
                w, h = hd.size
                assert min(w, h) >= 64 and max(w, h) <= 8192 and abs(w*32-h*48)*100 <= h*48
                assert hd.convert("RGBA").getextrema()[3] == (255, 255)
            asset_sha = sha(path.read_bytes())
        records.append({"index": i, "source": str(target.relative_to(Path('/output')).as_posix()),
                        "source_png_sha256": sha(data), "indices_sha256": sha(raw),
                        "asset": asset, "asset_sha256": asset_sha})
    q = json.dumps
    lines = ['// Code generated by tools/hd-terrain-prepare.py; DO NOT EDIT.', 'package main',
             'type hdTerrainProfile struct { SourceSHA, Asset, AssetSHA string }',
             'var hdTerrainProfiles = map[int]hdTerrainProfile{']
    for r in records:
        lines.append(f'{r["index"]}: {{{q(r["source_png_sha256"])}, {q(r["asset"])}, {q(r["asset_sha256"])}}},')
    lines += ['}', 'var hdTerrainPlaneSHA = [4]string{'+','.join(q(s) for s in trace['source_plane_sha256'])+'}', '']
    (project/"tools/hd-terrain-profiles.go").write_text('\n'.join(lines))
    result = {"classification": "local source/approved-art profiles; not a production pack schema", "source_count": 104,
              "reviewed_HD_count": len(REVIEWED), "pillow_version": pillow_version,
              "tool_sha256": sha(Path(__file__).read_bytes()), "extraction_sha256": sha(extraction_path.read_bytes()),
              "palette_verification_sha256": sha(evidence_path.read_bytes()), "source_plane_sha256": trace["source_plane_sha256"],
              "records": records}
    (root/"profiles.json").write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({"sources": 104, "reviewed_HD": len(REVIEWED)}))


if __name__ == "__main__":
    main()
