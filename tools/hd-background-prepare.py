"""校準五項既有手繪圖的有效美術區，生成共同不透明繪圖端的來源表。"""
import argparse
import hashlib
import json
import os
from collections import deque
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version


NAMES = ['BATTLE01.OZM','BATTLE02.OZM','OP2.OZM','OP4.OZM','OP8.OZM']


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def padding_from_top(data, width, height):
    seen = bytearray(len(data))
    queue = deque()
    for x in range(width):
        if data[x] == 0:
            seen[x] = 255
            queue.append(x)
    while queue:
        at = queue.popleft()
        x,y = at%width,at//width
        for xx,yy in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
            if 0 <= xx < width and 0 <= yy < height:
                n = yy*width+xx
                if not seen[n] and data[n] == 0:
                    seen[n] = 255
                    queue.append(n)
    return bytes(seen)


def main():
    assert Path('/.dockerenv').is_file() and os.getuid() == 1000 and pillow_version == '9.4.0'
    parser = argparse.ArgumentParser()
    parser.add_argument('--integrate',action='store_true')
    args = parser.parse_args()
    project,root = Path('/project'),Path('/output')
    assert root.stat().st_uid == root.stat().st_gid == 1000
    catalog = project/'workplace/hd-prototype/catalog'
    if args.integrate:
        manifest_path,review_path = root/'draft-manifest.json',root/'review.json'
        manifest,review = [json.loads(p.read_text()) for p in [manifest_path,review_path]]
        assert manifest['tool_sha256'] == sha(Path(__file__)) == sha(root/'prepare-source.txt')
        assert review['verified'] and review['approved_sources'] == NAMES and review['draft_manifest_sha256'] == sha(manifest_path)
        lines = ['// Code generated by tools/hd-background-prepare.py; DO NOT EDIT.','package main','import "image"',
                 'var hdGraphicsStaticProfiles = []hdGraphicsProfile{']
        for r in manifest['records']:
            assert sha(root/r['prepared']) == r['asset_sha256']
            planes = ','.join(json.dumps(x) for x in r['source']['plane_sha256'])
            rect = ','.join(map(str,r['paint_rect']))
            lines.append('{Source: graphicsSourceProfile{Name:'+json.dumps(r['name'])+',Width:'+str(r['source']['width'])+',Height:'+str(r['source']['height'])+',Planes:[]string{'+planes+'}},')
            lines.append('IndicesSHA:'+json.dumps(r['source']['indices_sha256'])+',Asset:'+json.dumps(r['asset'])+',AssetSHA:'+json.dumps(r['asset_sha256'])+',PaintRect:image.Rect('+rect+')},')
        lines += ['}','']
        target = project/'tools/hd-graphics-static-profiles.go'
        assert not target.exists() and target.parent.stat().st_uid == 1000
        target.write_text('\n'.join(lines))
        target = root/'profiles.json'
        assert not target.exists()
        target.write_text(json.dumps({**manifest,'classification':'reviewed static artwork geometry and common opaque source profiles',
                                     'draft_manifest_sha256':sha(manifest_path),'review_sha256':sha(review_path)},ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({'approved_static_sources':len(manifest['records'])}))
        return
    decoded = json.loads((catalog/'decoded/inventory.json').read_text())
    sources = {r['name']:r for r in decoded['records']}
    generated = {}
    for n in ['opening-generation.json','remaining-generation-v1.json']:
        for r in json.loads((catalog/'art'/n).read_text())['records']:
            generated[r['source']] = r
    palette = json.loads((catalog/'battle-frame/source-verification.json').read_text())['native_palette']
    prepared = root/'prepared'
    assert not prepared.exists()
    prepared.mkdir()
    records = []
    for name in NAMES:
        source,art = sources[name],generated[name]
        assert source['status'] == 'decoded'
        idx_path = catalog/'decoded'/(name+'.idx')
        assert sha(idx_path) == source['indices_sha256']
        data = idx_path.read_bytes()
        width,height = source['width'],source['height']
        assert len(data) == width*height
        raw_path = catalog/'art'/art['asset']
        assert sha(raw_path) == art['sha256'] and sha(catalog/'art'/art['prompt']) == art['prompt_sha256']
        raw = Image.open(raw_path).convert('RGB')
        paint_rect = (0,0,width,height)
        crop = (0,0,raw.width,raw.height)
        extra = {}
        if name.startswith('BATTLE'):
            paint_rect = (0,220,640,400)
            out = raw.resize((width*2,height*2),Image.Resampling.LANCZOS)
            padding = padding_from_top(data,width,height)
            assert padding.count(255) == data.count(0) == 148302
            mask = Image.frombytes('L',(width,height),padding).resize(out.size,Image.Resampling.NEAREST)
            out.paste((0,0,0),(0,0,*out.size),mask)
            extra.update(padding_index=0,padding_pixels=padding.count(255),padding_mask_sha256=hashlib.sha256(padding).hexdigest())
        elif name == 'OP2.OZM':
            paint_rect = (0,0,480,150)
            assert all(data[y*width+x] == 6 for y in range(height) for x in range(width) if x >= 480 or y >= 150)
            pixels = raw.getdata()
            mask = Image.new('L',raw.size)
            mask.putdata([255 if r+g > 96 else 0 for r,g,b in pixels])
            crop = mask.getbbox()
            assert crop and crop[:2] == (0,0) and 0.65*raw.width < crop[2] < 0.85*raw.width and 0.6*raw.height < crop[3] < 0.85*raw.height
            out = Image.new('RGB',(width*2,height*2),tuple(palette[6][:3]))
            out.paste(raw.crop(crop).resize((960,300),Image.Resampling.LANCZOS),(0,0))
            extra.update(padding_index=6,padding_pixels=width*height-480*150)
        elif name == 'OP4.OZM':
            mask = Image.frombytes('L',(width,height),bytes(255 if v not in [0,8] else 0 for v in data))
            paint_rect = mask.getbbox()
            assert paint_rect and 220 <= paint_rect[2]-paint_rect[0] <= 260 and 220 <= paint_rect[3]-paint_rect[1] <= 260
            bright = raw.convert('L').point(lambda v:255 if v > 40 else 0).getbbox()
            assert bright
            crop = (max(0,bright[0]-3),max(0,bright[1]-3),min(raw.width,bright[2]+3),min(raw.height,bright[3]+3))
            out = Image.new('RGB',(width*2,height*2),(0,0,0))
            out.paste(raw.crop(crop).resize(((paint_rect[2]-paint_rect[0])*2,(paint_rect[3]-paint_rect[1])*2),Image.Resampling.LANCZOS),
                      (paint_rect[0]*2,paint_rect[1]*2))
            extra.update(padding_indices=[0,8],source_nonblack_bounds=list(paint_rect))
        else:
            out = raw.resize((width*2,height*2),Image.Resampling.LANCZOS)
        path = prepared/(name.removesuffix('.OZM')+'-hd-calibrated-v1.png')
        out.save(path)
        original_path = catalog/'graphics'/(name+'-original.png')
        original = Image.open(original_path).convert('RGB')
        left,right = original.copy(),out.copy()
        left.thumbnail((600,375),Image.Resampling.NEAREST)
        right.thumbnail((600,375),Image.Resampling.LANCZOS)
        sheet = Image.new('RGB',(1280,420),(222,216,197))
        ImageDraw.Draw(sheet).text((8,8),name+'  original / calibrated HD',fill=(0,0,0))
        sheet.paste(left,(10,32));sheet.paste(right,(650,32))
        review = root/(name+'-review.png');sheet.save(review)
        records.append({'name':name,'source':source,'raw_asset':art['asset'],'raw_asset_sha256':sha(raw_path),
                        'prompt':art['prompt'],'prompt_sha256':art['prompt_sha256'],'raw_crop':list(crop),
                        'paint_rect':list(paint_rect),'prepared':str(path.relative_to(root)),
                        'asset':'static/'+path.name,'asset_sha256':sha(path),
                        'original_png_sha256':sha(original_path),'review':review.name,'review_sha256':sha(review),**extra})
    gallery = Image.new('RGB',(1280,3*340),(222,216,197))
    draw = ImageDraw.Draw(gallery)
    for i,r in enumerate(records):
        x,y = i%2*640,i//2*340
        draw.text((x+5,y+5),r['name'],fill=(0,0,0))
        im = Image.open(root/r['prepared']).crop(tuple(v*2 for v in r['paint_rect']))
        im.thumbnail((630,300),Image.Resampling.LANCZOS)
        gallery.paste(im,(x+5,y+30))
    path = root/'static-HD-gallery-v1.png';gallery.save(path)
    result = {'classification':'static source geometry calibration draft; not normal-path acceptance',
              'tool_sha256':sha(Path(__file__)),'decoded_inventory_sha256':sha(catalog/'decoded/inventory.json'),
              'records':records,'gallery':path.name,'gallery_sha256':sha(path),'scale':2}
    target = root/'draft-manifest.json';assert not target.exists()
    target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    (root/'prepare-source.txt').write_bytes(Path(__file__).read_bytes())
    print(json.dumps({'draft_sources':len(records),'geometry':[(r['name'],r['paint_rect'],r['raw_crop']) for r in records]}))


if __name__ == '__main__':
    main()
