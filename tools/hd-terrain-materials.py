"""依已核對地面索引的美術邊界製作 HD 圖；不解釋地形規則。"""
import argparse
import hashlib
import json
import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, __version__ as pillow_version


SCALE = 8
SIZE = (48*SCALE, 32*SCALE)
VERSION = 2
RECIPE = {'version':VERSION, 'scale':SCALE, 'boundary_blur_native_pixels':0.55, 'shade_blur_native_pixels':1.1,
          'isolated_surface_dither_max_pixels':4,
          'soil_indices':[2,3,10], 'water_indices':[6,9,14],
          'shade_values':{'0':64,'1':92,'8':64,'5':216,'13':244,'7':255,'10':255}}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def sha(path):
    return digest(path.read_bytes())


def save_image(im, path):
    if path.exists():
        assert path.stat().st_uid == 1000 and Image.open(path).convert('RGB').tobytes() == im.convert('RGB').tobytes(), path
    else:
        im.save(path)


def mask(raw, classes):
    return bytes(255 if value in classes else 0 for value in raw)


def surface_mask(raw):
    """少量孤立色點屬材質細節；保留與大塊草地相連的岸線。"""
    out, seen = bytearray(raw), set()
    for start,value in enumerate(raw):
        if value or start in seen:
            continue
        queue = [start];seen.add(start)
        for n in queue:
            x,y = n%48,n//48
            for xx,yy in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
                nn = yy*48+xx
                if 0<=xx<48 and 0<=yy<32 and nn not in seen and raw[nn] == 0:
                    seen.add(nn);queue.append(nn)
        if len(queue) <= RECIPE['isolated_surface_dither_max_pixels']:
            for n in queue:
                out[n] = 255
    return bytes(out)


def enlarged(raw, blur):
    return Image.frombytes('L',(48,32),raw).filter(ImageFilter.GaussianBlur(blur)).resize(SIZE,Image.Resampling.BICUBIC)


def main():
    assert Path('/.dockerenv').is_file() and os.getuid() == 1000 and pillow_version == '9.4.0'
    parser = argparse.ArgumentParser()
    parser.add_argument('--integrate',action='store_true')
    args = parser.parse_args()
    project, terrain = Path('/project'), Path('/output')
    root = terrain/'materials'
    assert terrain.stat().st_uid == root.stat().st_uid == 1000
    baseline_path = terrain/'prepared/profiles.json'
    baseline = json.loads(baseline_path.read_text())
    assert baseline['reviewed_HD_count'] == 8 and baseline['source_count'] == 104
    assert baseline['tool_sha256'] == sha(project/'tools/hd-terrain-prepare.py')
    if args.integrate:
        manifest_path, review_path = root/f'draft-manifest-v{VERSION}.json', root/f'review-v{VERSION}.json'
        manifest, review = json.loads(manifest_path.read_text()), json.loads(review_path.read_text())
        assert review['verified'] and review['draft_manifest_sha256'] == sha(manifest_path)
        assert review['reviewed_indices'] == list(range(104))
        assert manifest['tool_sha256'] == sha(Path(__file__)) and manifest['baseline_sha256'] == sha(baseline_path)
        for record in manifest['records']:
            path = terrain/'art'/record['asset'] if record['inherited'] else root/f'drafts-v{VERSION}'/record['asset']
            assert sha(path) == record['asset_sha256'], path
        lines = ['// Code generated by tools/hd-terrain-materials.py; DO NOT EDIT.','package main',
                 'type hdTerrainProfile struct { SourceSHA, Asset, AssetSHA string }',
                 'var hdTerrainProfiles = map[int]hdTerrainProfile{']
        q = json.dumps
        for record in manifest['records']:
            lines.append(f'{record["index"]}: {{{q(record["source_png_sha256"])}, {q(record["asset"])}, {q(record["asset_sha256"])}}},')
        lines += ['}','var hdTerrainPlaneSHA = [4]string{'+','.join(q(s) for s in baseline['source_plane_sha256'])+'}','']
        target = project/'tools/hd-terrain-profiles.go'
        assert target.stat().st_uid == 1000
        target.write_text('\n'.join(lines))
        result = {'classification':'reviewed complete floor source/HD profiles; normal path sampled separately',
                  'tool_sha256':sha(Path(__file__)),'baseline_sha256':sha(baseline_path),
                  'draft_manifest_sha256':sha(manifest_path),'review_sha256':sha(review_path),
                  'source_count':104,'reviewed_HD_count':104,'source_plane_sha256':baseline['source_plane_sha256'],
                  'records':manifest['records']}
        target = root/'profiles.json'
        assert not target.exists(), 'preserve previous integration metadata'
        target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({'integrated_sources':104,'unique_assets':len({r['asset'] for r in result['records']})}))
        return
    generation_path = root/'generation.json'
    generation = json.loads(generation_path.read_text())
    materials = {}
    for record in generation['records']:
        path = root/record['asset']
        assert sha(path) == record['sha256'] and sha(root/record['prompt']) == record['prompt_sha256']
        with Image.open(path) as im:
            assert im.convert('RGBA').getextrema()[3] == (255,255)
            materials[record['material']] = im.convert('RGB').resize(SIZE,Image.Resampling.LANCZOS)
    assert set(materials) == {'soil','water-deep','water-light'}
    grass_path = terrain/'art/floor-000-hd-b-v1.png'
    assert sha(grass_path) == baseline['records'][0]['asset_sha256']
    grass = Image.open(grass_path).convert('RGB').resize(SIZE,Image.Resampling.LANCZOS)
    idx_path = project/'workplace/hd-prototype/catalog/decoded/MAP_CHIP.OZM.idx'
    idx = idx_path.read_bytes()
    assert sha(idx_path) == '0e4e6f63e71a39309e21888724ed0e4da29e8f58cfb49b55095340132f4b010b'
    drafts = root/f'drafts-v{VERSION}'
    drafts.mkdir(exist_ok=True)
    assert drafts.stat().st_uid == 1000
    records, owners = [], {}
    for source in baseline['records']:
        if source['asset']:
            owners[source['indices_sha256']] = source['index']
    by_index = {r['index']:r for r in baseline['records']}
    generated_by_index = {}
    source_masks = {}
    for source in baseline['records']:
        i = source['index'];x,y = i%13*48,i//13*32
        raw = b''.join(idx[v*640+x:v*640+x+48] for v in range(y,y+32))
        assert digest(raw) == source['indices_sha256'] and len(raw) == 1536
        source_path = terrain/source['source']
        assert sha(source_path) == source['source_png_sha256']
        soil_raw = mask(raw,{2,3,10}) if 2 in raw or 3 in raw else bytes(1536)
        water_raw = mask(raw,{6,9,14}) if 6 in raw or 14 in raw else bytes(1536)
        source_masks[i] = (soil_raw,water_raw)
        soil_clean,water_clean = surface_mask(soil_raw),surface_mask(water_raw)
        owner = owners.setdefault(source['indices_sha256'],i)
        inherited = bool(by_index[owner]['asset'])
        if inherited:
            asset = by_index[owner]['asset'];asset_sha = by_index[owner]['asset_sha256']
        elif owner != i:
            asset,asset_sha = generated_by_index[owner]
        else:
            soil = enlarged(soil_clean,RECIPE['boundary_blur_native_pixels'])
            water = enlarged(water_clean,RECIPE['boundary_blur_native_pixels'])
            light_raw = bytes(255 if value == 14 else 100 if value == 9 else 0 for value in raw)
            light = enlarged(light_raw,RECIPE['shade_blur_native_pixels'])
            water_texture = Image.composite(materials['water-light'],materials['water-deep'],light)
            painted = Image.composite(materials['soil'],grass,soil)
            painted = Image.composite(water_texture,painted,water)
            # 原版低頻明暗控制材質光度；不保留原版像素紋理。
            shade_raw = bytes(RECIPE['shade_values'].get(str(value),244) for value in raw)
            shade = enlarged(shade_raw,RECIPE['shade_blur_native_pixels']).tobytes()
            data = painted.tobytes()
            painted = Image.frombytes('RGB',SIZE,bytes(min(255,(v*shade[n//3]+122)//244) for n,v in enumerate(data)))
            asset = f'floor-{i:03d}-hd-b-v{VERSION}.png'
            save_image(painted,drafts/asset)
            asset_sha = sha(drafts/asset)
            generated_by_index[i] = (asset,asset_sha)
        records.append({**source,'asset':asset,'asset_sha256':asset_sha,'inherited':inherited,
                        'asset_source_index':owner,'soil_mask_sha256':digest(soil_raw),'water_mask_sha256':digest(water_raw),
                        'soil_native_pixels':soil_raw.count(255),'water_native_pixels':water_raw.count(255),
                        'clean_soil_mask_sha256':digest(soil_clean),'clean_water_mask_sha256':digest(water_clean),
                        'soil_surface_dither_pixels':soil_clean.count(255)-soil_raw.count(255),
                        'water_surface_dither_pixels':water_clean.count(255)-water_raw.count(255)})
    # 同圖形的道路／河道配對提供獨立的索引類別正對照。
    paired = []
    for soil_index in range(38,59):
        water_index = soil_index+21
        if source_masks[soil_index][0] == source_masks[water_index][1]:
            paired.append([soil_index,water_index])
    assert paired == [[i,i+21] for i in range(38,50)]
    pages = []
    generated_sheet = Image.new('RGB',(13*144,8*120),(222,216,197))
    gd = ImageDraw.Draw(generated_sheet)
    for page in range(7):
        sheet = Image.new('RGB',(4*304,4*128),(222,216,197)); draw = ImageDraw.Draw(sheet)
        for slot,record in enumerate(records[page*16:(page+1)*16]):
            x,y = slot%4*304,slot//4*128
            original = Image.open(terrain/record['source']).convert('RGB').resize((144,96),Image.Resampling.NEAREST)
            hd_path = terrain/'art'/record['asset'] if record['inherited'] else drafts/record['asset']
            hd = Image.open(hd_path).convert('RGB').resize((144,96),Image.Resampling.LANCZOS)
            draw.text((x+4,y+4),f"floor {record['index']:03d}  original / HD",fill=(0,0,0))
            sheet.paste(original,(x+4,y+24));sheet.paste(hd,(x+156,y+24))
            j = record['index']; gx,gy = j%13*144,j//13*120
            gd.text((gx+4,gy+4),f'floor {j:03d}',fill=(0,0,0));generated_sheet.paste(hd,(gx,gy+20))
        name = f'review-v{VERSION}-page-{page+1:02d}.png'
        save_image(sheet,root/name);pages.append({'path':name,'sha256':sha(root/name)})
    gallery = root/f'floor-material-gallery-v{VERSION}.png'
    save_image(generated_sheet,gallery)
    result = {'classification':'source-boundary material composition drafts, not original terrain rules or runtime receipts',
              'tool_sha256':sha(Path(__file__)),'baseline_sha256':sha(baseline_path),
              'generation_sha256':sha(generation_path),'source_indices_sha256':sha(idx_path),
              'grass_asset':'workplace/hd-prototype/catalog/terrain/art/floor-000-hd-b-v1.png','grass_asset_sha256':sha(grass_path),
              'recipe':RECIPE,'source_count':104,'new_source_cases':96,'new_unique_images':len(generated_by_index),
              'paired_road_water_masks':paired,'review_pages':pages,'gallery':gallery.name,'gallery_sha256':sha(gallery),
              'records':records}
    target = root/f'draft-manifest-v{VERSION}.json'
    assert not target.exists(), 'preserve previous draft manifest'
    target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'sources':104,'new_sources':96,'new_unique_images':len(generated_by_index),'paired_masks':len(paired)}))


if __name__ == '__main__':
    main()
